<div itemprop="text">
<p>Here are some of the influences, decisions and processes that went into creating some of the music and lyrics for <i>Impermanence</i>.</p>

<hr>

<h2>The Music (by Roger)</h2>

<p>This one was tough and the last song completed for the EP. It was the third song I had written and was my favorite musically, so I really pushed to get this one done. As a whole, the original musical direction that I wanted to explore for this tMitG release, in addition to analog synth sounds, was a downtempo-dirge-doom vibe, in many ways inspired by artists like <a rel="noopener noreferrer" href="https://evivine.bandcamp.com/album/black-light-white-dark" target="_blank">Evi Vine</a> and <a rel="noopener noreferrer" href="https://grveband.bandcamp.com/track/resign-your-fate-radio-edit" target="_blank">Gr^ve</a>. That vibe can still be heard here and also in “Oderint dum metuant.” The original version of “The Beginning of All Things” was also that way before we changed it to include the upbeat mid-section.</p>

<p>I can say with certainty that Summer worked very hard and with a lot of frustration to complete this song: the slow tempo and dirgey nature wasn’t working for her. I don’t know what changed, but what she eventually produced blew me away. Perhaps the choice to sing faster and not match the music’s pace was a big part of it? Either way, the end result is my favorite vocal performance on the album: strong, passionate, emotive.</p>

<hr>

<h2>The Lyrics (by Summer)</h2>

<p>Gosh I hated this thing at first. I was just so frustrated with it for so long. It’s like that part of <i>Pee Wee’s Big Adventure</i> where the pet store is on fire and he keeps running in to save the animals and he keeps seeing the snakes and shuddering and saves all the other cute animals. But ultimately, finally, he realizes that the snakes need saving too? This song was my snakes. I originally tried some other lyrics and vocal melody in this song but they just didn’t fit. So I scrapped everything and started fresh with the lyrics you hear. I didn’t rehearse it overly much. I wanted it to be raw and unrehearsed, which you can hear in the fact that I don’t sing the chorus the same way each time - mostly because I couldn’t quite remember what I had done the first time. This is the most personal song on the album. I don’t often write about my own life experiences. I often inhabit another character or describe a scene or idea and I am most often inspired by myths, legends, games, and stories. Some examples of this are songs like “Words in Heaven Lost” (Hamlet), “Her Face” (Helen of Troy), “Otherworld” (His Dark Materials), “Winter Fell” (Game of Thrones), or more obvious ones like “Icarus” or “Wonderland” or more recently “Prophetic Bird” (Gamayun of Russian folklore) and “Courage Power and Wisdom” (my all-time favorite game, the Legend of Zelda) and nearly every song on “Before and After the Storm.” But this one is autobiographical and really helped me process some things I went through 2021-2023. Basically once again, things that are outside of your control, things you didn’t ask for but have to deal with anyway.</p>
