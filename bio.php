<h1 class="wai">the Machine in the Garden Biography</h1>

<div class="twocols">
<p>the Machine in the Garden is the gothic/etherealwave/darkwave duo of Roger Fracé and Summer Bowman currently residing in Austin, Texas. Over three decades and ten studio releases, the band has built one of the genre’s most distinctive catalogs: music that moves between atmospheric darkness, goth rock, electronic, and ethereal without ever losing its unique identity.</p>

<p>the Machine in the Garden began in 1992 when Roger Fracé started building what would become <i>Veils and Shadows EP</i>. Released in 1994, the four tracks crossed goth, new wave, and industrial. Critics praised its ability to move from “relaxing and refreshing” openings to raw, unsettling peaks and back again, with one noting it was “a notch above what many internationally-known bands are doing right now.”</p>

<p>Three years later, vocalist Summer Bowman joined Fracé, and the duo released <i>Underworld</i> (1997) on their own label, Deus ex Musica: a label they would later return to for all of their independent releases. <i>Underworld</i> revealed the full range that would define the band: from ethereal to darkwave, and blending hard-edged electronics and goth sensibilities with Bowman’s voice as the thread running through all of it. the Machine in the Garden had placed their mark on the goth scene with a sound that was impossible to categorize.</p>

<p>New York’s Middle Pillar Presents label took notice and signed the band, releasing four albums in six years: <i>One Winter’s Night…</i> (1999), which drew the sound into a more cohesive ethereal feel; <i>Out of the Mists</i> (2000), further solidifying them as an etherealwave presence; and <i>Asphodel</i> (2002), a push into the darker sounds the band was known for. But it was <i>Shadow Puppets</i> (2005) that brought everything together. Widely considered the band’s defining statement from this era, reviewers called it “a quantum leap forward,” praising its seamless blend of electronics and ethereal melodies. It was dynamic and anthemic where it needed to be, but also had quiet and introspective moments.</p>

<p>In 2007, the band returned to operating under their own Deus ex Musica imprint, releasing the 15th anniversary retrospective <i>XV</i>, a collection of remixed songs, unreleased tracks, and two new original songs.</p>

<p>Four years later, <i>Before and After the Storm</i> (2011) saw the band return with a harder-edged and more rhythmically driven sound. It landed at #3 on two major year-end goth/darkwave lists and confirmed that time away had only sharpened the band. Bowman’s voice remained the emotional center, while Fracé’s production balanced complex and unique musical elements.</p>

<p><i>Places in Between</i> arrived in 2020 as something larger still: thirteen tracks, over an hour, and arguably the most ambitious of their career. ReGen Magazine called it a potential “magnum opus,” praising Fracé’s “sophisticated instrumentation and refined production” alongside Bowman’s “masterful command of lyrical and vocal harmony.” Other critics described it as a “long cinematic experience.” The band did what they do best: shifting between goth rock, electronic ethereal, and classically inflected music and vocal writing without losing coherence or identity.</p>

<p>Six years on, <i>Impermanence</i> picks up from there: tighter in focus, stripped down to just the machine and voice, but still as rich, engaging, and emotional as everything that came before it. All ten releases, including <i>Impermanence</i>, are available on Bandcamp and all major streaming platforms.</p>

<p>The name “the Machine in the Garden” has always carried meaning, invoking the collision between technology and nature, the mechanical and the spiritual. That tension runs through everything. Thirty-plus years in, the band remains what it has always been: two people operating entirely on their own terms, creating music built to last.</p>

