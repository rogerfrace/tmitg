<p>Here are some of the influences, decisions and processes that went into creating some of the music and lyrics for <i>Impermanence</i>.</p>

<hr>

<h2>The Music (by Roger)</h2>

<p>Written literally to be an intro to the EP, and with a working title of “Intro” even after it was completed, this is one of two songs on <i>Impermanence</i> inspired by “Spiritus ex Obitus Sanctus” which I wrote and recorded in 1995 and released on Underworld. The original idea was what you hear in the first 70 seconds: the same sound panned, but one side gradually pitch bends a full octave over one minute while gradually panning toward center (but never getting there).</p>

<p>One thing I like doing, and have done since the days of the Vision music software in the 90s, is manipulating space or sound quality gradually over time. Which is something that happens in “Spiritus” and something I did frequently through this EP: gradually manipulating not just panning but filters and modulators  over the course of a song, to change the nature of the sound between the beginning and end. Of course, me being me, I picked the track back up later and added onto it: adding the piano, TR-606 drum samples, and the arpeggios for the climactic ending.</p>

<p>When I gave it to Summer, I presented it as an intro track, but with an indecisive direction. I would be perfectly happy leaving it as an instrumental, or she could add some wailing or spoken vocal (or both), but I really didn’t have a preference. She added the wailing first, and we liked the result, and perhaps a week later she added the spoken part. The final result I think is a great intro piece for both the musical style and lyrical themes of the EP. This was the last song written for the EP, but not the last to be completed.</p>

<hr>

<h2>The Lyrics (by Summer)</h2>

<p>Both the wailing and the spoken words were unrehearsed and off the cuff. Dru (my musical partner for Mirabilis) calls it channeling. I can sometimes just go in, step up to the mic and sing something in one go.</p>

<p>The lyrics were pre-prepared, however. Throughout the writing of these songs I had a collection of lyrics floating around. After recording all the vocals for all the songs, I had a little batch of lyrics left that didn’t fit into that song and so I literally just tossed them into this piece. I didn’t rehearse it, I didn’t prep or practice in any way. I just went in, we hit record, I said them, we saved it and moved on. Done in one take!</p>
