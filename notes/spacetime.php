<div itemprop="text">
<p>Here are some of the influences, decisions and processes that went into creating some of the music and lyrics for <i>Impermanence</i>.</p>

<hr>

<h2>The Music (by Roger)</h2>

<p>This was the 5th song written for <i>Impermanence</i> and the third to be completed. It was the most recently completed track when we released it in May 2026 as a single. We felt it was a strong track and the “Space-Time” theme would make for a fairly simple lyric video on a short timeline to target a World Goth Day release and re-introduce ourselves after a nearly 6 year absence.</p>

<p>You may be surprised to hear this song was also inspired by “Spiritus ex Obitus Sanctus” from <i>Underworld</i>&mdash;Summer certainly was! In many ways the concept is very similar to “The Unwritten Way” in that I picked a single note, C, and just mostly stuck with it, choosing instead to manipulate sounds, including drums, over time, and eventually adding the basic lead riff that shows up twice in the song. Some of the idea, too, was to keep the music simple and really give Summer a lot of space to work her magic.</p>

<hr>

<h2>The Lyrics (by Summer)</h2>

<p>Both the wailing and the spoken words were unrehearsed and off the cuff. Dru (my musical partner for Mirabilis) calls it channeling. I can sometimes just go in, step up to the mic and sing something in one go.</p>

<p>The lyrics were pre-prepared, however. Throughout the writing of these songs I had a collection of lyrics floating around. After recording all the vocals for all the songs, I had a little batch of lyrics left that didn’t fit into that song and so I literally just tossed them into this piece. I didn’t rehearse it, I didn’t prep or practice in any way. I just went in, we hit record, I said them, we saved it and moved on. Done in one take!</p>
