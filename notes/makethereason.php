<div itemprop="text">
<p>Here are some of the influences, decisions and processes that went into creating some of the music and lyrics for <i>Impermanence</i>.</p>

<hr>

<h2>The Music (by Roger)</h2>

<p>This is kinda a weird one. The concept was not just to change time signatures between 3/4 and 4/4 through the song, but to mix them and see how they would interplay with each other over time. For example, the main bass riff that opens the song is 3/4, but the lead pads are 4/4.</p>

<p>Honestly, I found the music somewhat awkward and forced and it was not a favorite, so I was surprised when Summer picked it up to work on it. What she ended up doing with her vocals worked some sort of magic, because the vocals ended up tying the whole song together and making it sound cohesive. It ended up being one of my favorite tracks.</p>

<hr>

<h2>The Lyrics (by Summer)</h2>

<p>I’m actually a pretty big fan of Aimee Mann and I was listening to her episode of the Audible podcast “Words + Music” in January 2023. In this podcast she explores the link between art and trauma, which, for sure is something we’re dealing with in this EP. And at one point in it she said “I know the cliche is that ‘everything happens for a reason’ but I tend to think things might just happen, and then we make the reason, either out of want or necessity. And I often wonder if this is what art is for.” That statement “make the reason” really stuck with me and especially when bad things happen in your life, often people will think they are being really helpful and will say “oh well, everything happens for a reason” and I’m sorry, but that really sucks. When you’re in the thick of it, it feels awful that there would be <i>reason</i> for really tragic things. So I wanted to explore what it looks like to look back and figure out the reason and it just felt right thematically with the lyrical content of a lot of these songs exploring trauma and grief.</p>
